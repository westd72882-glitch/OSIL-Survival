#pragma once
// ==================== ШУМ ПЕРЛИНА ====================
// Основа процедурного мира: карта высот, влажность и температура — три независимых
// поля шума, из которых уже выводятся биомы (см. src/World/WorldGen.*).
//
// Почему собственная реализация, а не библиотека: генерация обязана давать
// БИТ-В-БИТ одинаковый результат на сервере и на клиенте (клиент строит террейн
// локально по сиду, сервер по нему же считает коллизии). Значит нужен фиксированный
// алгоритм с известной таблицей перестановок, порождаемой из сида, а не «какой-то
// шум из зависимости, который может смениться при обновлении».
//
// Слои поверх базового Перлина:
//   fbm     — сумма октав, обычный рельеф (холмы разного масштаба);
//   ridged  — «хребты»: 1-|noise|, даёт острые горные гребни;
//   billow  — |noise|, округлые дюны для пустыни;
//   warp    — смещение координат другим шумом, ломает «сеточность» Перлина.
#include <cstdint>

struct NoiseParams {
    float frequency  = 1.0f / 512.0f; // 1/метры: период базовой октавы
    int   octaves    = 5;
    float lacunarity = 2.0f;          // во сколько раз растёт частота каждой октавы
    float gain       = 0.5f;          // во сколько раз падает амплитуда каждой октавы
};

class PerlinNoise {
public:
    PerlinNoise() { reseed(0); }
    explicit PerlinNoise(uint64_t seed) { reseed(seed); }

    // Пересобирает таблицу перестановок из сида (перемешивание Фишера — Йетса на PCG32).
    void reseed(uint64_t seed);

    // Базовый градиентный шум, диапазон примерно [-1,1].
    float noise2(float x, float y) const;

    // Фрактальный шум: сумма октав, нормирована к [-1,1].
    float fbm(float x, float y, const NoiseParams& p) const;
    // Хребтовой шум, [0,1]: единицы на гребнях.
    float ridged(float x, float y, const NoiseParams& p) const;
    // «Пузырчатый» шум, [0,1]: мягкие купола, хорош для дюн.
    float billow(float x, float y, const NoiseParams& p) const;

    // Искажение координат другим слоем шума (domain warp). strength — в метрах.
    void warp(float& x, float& y, float frequency, float strength) const;

private:
    uint8_t perm_[512] = {0}; // удвоенная таблица: индексация без взятия остатка
    float gradDot_(int hash, float x, float y) const;
};

// Удобный общий помощник: перевести значение из [-1,1] в [0,1].
float noiseTo01(float v);
