#pragma once
// ==================== ДЕТЕРМИНИРОВАННАЯ СЛУЧАЙНОСТЬ ====================
// Требование к миру выживания: один и тот же сид ОБЯЗАН давать один и тот же мир на
// сервере и у всех клиентов, на любой платформе и в любом порядке обхода. Поэтому
// std::mt19937/rand() здесь не годятся: их результат зависит от порядка вызовов и от
// реализации распределений в конкретной libstdc++/libc++.
//
// Решение — два инструмента:
//   1. Rng (PCG32) — быстрый поток чисел там, где порядок вызовов фиксирован (симуляция).
//   2. hashCoords()/rngForCell() — «случайность как функция от координат»: значение для
//      клетки (x,z) считается независимо от соседей. Именно так расставляются деревья,
//      камни и руда: чанк можно сгенерировать в любой момент и получить то же самое.
#include <cstdint>

// ---- SplitMix64: перемешиватель для порождения сидов из чисел (в т.ч. из координат).
uint64_t splitMix64(uint64_t x);

// ---- PCG32 (permuted congruential generator): 64 бита состояния, 32 бита выхода.
// Быстрее и лучше по статистике, чем LCG, и полностью воспроизводим — вся арифметика
// на беззнаковых целых фиксированной ширины.
struct Rng {
    uint64_t state = 0x853c49e6748fea9bULL;
    uint64_t inc   = 0xda3e39cb94b95bdbULL; // должен быть нечётным

    Rng() = default;
    explicit Rng(uint64_t seed, uint64_t sequence = 0xda3e39cb94b95bdbULL);

    uint32_t nextU32();
    uint64_t nextU64();
    // [0,1) с шагом 2^-24 — точность float здесь исчерпывающая.
    float nextFloat();
    // [lo,hi)
    float nextRange(float lo, float hi);
    // [0,bound) без смещения (отбрасываем «хвост» диапазона).
    uint32_t nextBelow(uint32_t bound);
    // [lo,hi] включительно
    int nextInt(int lo, int hi);
    // true с вероятностью p (0..1)
    bool chance(float p);
};

// Хеш координат клетки с солью: соль разводит между собой независимые слои
// (деревья, камни, руда, животные) — иначе все они лягут в одни и те же точки.
uint64_t hashCoords(int64_t x, int64_t z, uint64_t seed, uint64_t salt);
// Готовый генератор для клетки: детерминирован и не зависит от порядка обхода чанков.
Rng rngForCell(int64_t x, int64_t z, uint64_t seed, uint64_t salt);
// Разбор сида из строки конфига: число — как есть; слово — хешируется (сид "osil").
uint64_t seedFromString(const char* text);
