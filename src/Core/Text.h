#pragma once
// ==================== ТЕКСТОВЫЕ УТИЛИТЫ ====================
// Весь интерфейс сервера и отчёты — на русском, то есть UTF-8, где буква занимает два
// байта. Обычный printf("%-22s") считает БАЙТЫ, поэтому колонки в списках монументов и
// ресурсов разъезжаются тем сильнее, чем длиннее русское название. Здесь — выравнивание
// по символам, а не по байтам.
#include <cstddef>
#include <string>

// Число символов (кодовых точек) в UTF-8 строке.
size_t utf8Length(const std::string& s);
// Дополнить строку пробелами справа до width символов (длиннее — не обрезается).
std::string padRightUtf8(const std::string& s, size_t width);
