#pragma once
// ==================== SHA-256 ====================
// Нужен ровно для одного: хранить пароли аккаунтов закрытого теста не открытым текстом.
// Реализация своя и без зависимостей — сервер собирается на голой машине в докере, где
// нет ни OpenSSL, ни менеджера пакетов для C++, а тянуть библиотеку ради одной функции
// хеширования незачем.
//
// Это НЕ полноценная схема хранения паролей: настоящая (bcrypt/argon2 с растяжением)
// появится вместе с настоящими аккаунтами. Здесь соль на аккаунт плюс один проход
// SHA-256 — достаточно, чтобы пароли не лежали в файле как есть, и честно записано,
// чем это отличается от взрослого решения.
#include <string>

// Возвращает хеш в виде 64 шестнадцатеричных символов.
std::string sha256Hex(const std::string& data);
