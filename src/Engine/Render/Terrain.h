#pragma once
// ==================== ТЕРРЕЙН: ПОТОКОВАЯ ПОДГРУЗКА ЧАНКОВ ====================
// В A.N.O.D.E рельеф был картой 300x300 м, нарезанной на фиксированные куски: их можно
// было построить все сразу при старте. В OSIL карта 4000x4000 м — это в 178 раз большая
// площадь, и построить её целиком нельзя ни по памяти (десятки миллионов вершин), ни по
// времени старта. Поэтому здесь переписанный вариант: чанки строятся и выбрасываются на
// ходу, вокруг игрока, и не больше нескольких штук за кадр — иначе телефон «икает» при
// каждом шаге.
//
// Движок НЕ знает, откуда берётся высота: игра передаёт функцию (в OSIL она читает
// World, тот же детерминированный мир, что и на сервере). Так рендер остаётся
// независимым от игровой логики.
#include "Mesh.h"
#include "../../Core/Math.h"

// Функция высоты рельефа в мировых координатах (метры).
typedef float (*TerrainHeightFn)(float x, float z);

struct TerrainStreamConfig {
    float worldSize   = 4000.0f; // сторона карты
    float chunkSize   = 64.0f;   // сторона чанка в метрах
    int   chunkRes    = 24;      // сегментов по стороне чанка (шаг ≈ 2.7 м)
    float uvTilePerMeter = 0.25f;// сколько раз тайлится текстура земли на метр
    int   buildsPerFrame = 2;    // сколько чанков строим за кадр (защита от рывков)
};

void terrainInit(const TerrainStreamConfig& cfg, TerrainHeightFn heightFn);
void terrainShutdown();

// Достраивает недостающие чанки вокруг камеры и выбрасывает уехавшие за пределы
// radius * 1.5. Вызывать раз в кадр ДО отрисовки.
void terrainUpdate(Vec3 camPos, float radius);

// Рисует чанки в радиусе. Возвращает количество отрисованных (для отладки).
int  terrainRender(Vec3 camPos, float radius);

// Сколько чанков сейчас в памяти и сколько ждёт постройки — для отладочной строки.
int terrainLoadedChunks();
int terrainPendingChunks();
