#pragma once
// ==================== ТЕКСТУРЫ БЛОКОВ ====================
// Все текстуры блоков лежат в ОДНОМ массиве текстур (GL_TEXTURE_2D_ARRAY), а не в
// атласе. Причина практическая: у атласа соседние клетки «протекают» друг в друга при
// мипмаппинге и билинейной фильтрации — по краям блоков появляется чужая кайма. В
// массиве каждый слой самостоятелен, повторение и мипмапы работают как надо, а рисуется
// он тем же одним вызовом, что и атлас.
//
// Слоёв немного: несколько типов блоков делят одну текстуру и различаются ЦВЕТОВЫМ
// ФИЛЬТРОМ — песок, снег и трава сделаны из одной картинки грунта (так и просил
// художник), поэтому память под текстуры почти не растёт.
#include "GL.h"
#include "../../World/Blocks.h"

// Загружает текстуры из assets/. Возвращает false, если не нашлась ни одна: игра тогда
// рисует блоки плоским цветом, как раньше, — правило проекта «запускаться без ассетов».
bool blockTexturesInit();
void blockTexturesShutdown();
bool blockTexturesReady();
GLuint blockTextureArray();

// Слой массива для блока и цветовой фильтр поверх текстуры.
int  blockTextureLayer(Block b);
void blockTextureTint(Block b, float& r, float& g, float& bl);
