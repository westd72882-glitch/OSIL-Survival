#pragma once
// ==================== БИОМЫ ====================
// Биом — это функция трёх полей шума: высота, влажность, температура (как в ТЗ).
// Он определяет: что здесь растёт и добывается, как быстро игрок мёрзнет/жарится,
// какой цвет у клетки на карте и какие животные спавнятся.
//
// Классификация намеренно сделана таблицей правил, а не деревом if-ов вразброс:
// правила проверяются по порядку, первое подошедшее выигрывает — так поведение
// генератора можно прочитать и изменить в одном месте.
#include <cstdint>

enum class Biome : uint8_t {
    Ocean = 0,   // ниже уровня воды
    Beach,       // побережье
    Grassland,   // травянистая равнина
    Forest,      // лес
    Desert,      // пустыня
    Swamp,       // болото
    Snow,        // снежные горы
    COUNT
};

struct BiomeInfo {
    const char* id;        // короткий идентификатор для протокола и БД
    const char* nameRu;    // название для интерфейса
    uint8_t r, g, b;       // цвет на карте предпросмотра и на мини-карте
    float treeDensity;     // множитель плотности деревьев (0..1+)
    float rockDensity;     // валуны и скалы
    float bushDensity;     // кусты/ягоды/грибы/тыквы
    float oreChance;       // доля рудных жил среди каменных объектов
    float sulfurChance;    // доля серных жил среди каменных объектов
    // Температура окружения, °C (базовая; ночью и в дождь ниже — 3-й этап, метаболизм).
    float ambientTemp;
    // Множитель расхода воды: в пустыне жажда растёт быстрее.
    float thirstRate;
};

const BiomeInfo& biomeInfo(Biome b);
const char* biomeName(Biome b);

// Классификация по нормализованным полям:
//   height01     — высота, 0 на уровне моря .. 1 на максимуме карты
//   moisture01   — влажность 0..1
//   temperature01— температура 0..1 (0 — мороз, 1 — зной)
//   underwater   — точка ниже уровня воды
//   beach        — точка в прибрежной полосе
Biome classifyBiome(float height01, float moisture01, float temperature01,
                    bool underwater, bool beach);
