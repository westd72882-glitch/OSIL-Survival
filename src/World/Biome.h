#pragma once
// ==================== БИОМЫ ====================
// Биом определяет: что здесь растёт и добывается, как быстро игрок мёрзнет и хочет пить,
// какой цвет у клетки на карте.
//
// Биомов ровно три (плюс океан и полоса пляжа), и они разложены КРУПНЫМИ ЗОНАМИ, а не
// пятнами: пустыня — на западе, зима — на востоке, равнина — на севере и в центре.
// Прежний вариант «биом как функция влажности и температуры» давал чересполосицу, где
// болото сидело в лесу, а снег — рядом с песком: по такой карте невозможно
// ориентироваться и незачем путешествовать.
#include <cstdint>

enum class Biome : uint8_t {
    Ocean = 0,   // ниже уровня воды
    Beach,       // побережье
    Grassland,   // равнина: трава, редкие деревья
    Desert,      // пустыня: песок
    Snow,        // зима: снег
    COUNT
};

struct BiomeInfo {
    const char* id;        // короткий идентификатор для протокола и БД
    const char* nameRu;    // название для интерфейса
    uint8_t r, g, b;       // цвет на карте предпросмотра и на мини-карте
    float treeDensity;     // множитель плотности деревьев (0..1+)
    float rockDensity;     // валуны и скалы
    float bushDensity;     // кусты/ягоды/грибы/тыквы
    float oreChance;       // доля рудных жил среди каменных объектов
    float sulfurChance;    // доля серных жил среди каменных объектов
    // Температура окружения, °C (базовая; ночью и в дождь ниже — 3-й этап, метаболизм).
    float ambientTemp;
    // Множитель расхода воды: в пустыне жажда растёт быстрее.
    float thirstRate;
};

const BiomeInfo& biomeInfo(Biome b);
const char* biomeName(Biome b);

// Классификация. zone01 — принадлежность к зоне: 0 — крайний запад (пустыня),
// 1 — крайний восток (зима), середина — равнина. Границу зон генератор искажает шумом,
// поэтому она не выглядит прочерченной по линейке.
//   height01   — высота, 0 на уровне моря .. 1 на максимуме карты
//   zone01     — положение в зональной раскладке 0..1
//   underwater — точка ниже уровня воды
//   beach      — точка в прибрежной полосе
Biome classifyBiome(float height01, float zone01, bool underwater, bool beach);
